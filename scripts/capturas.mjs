// Capturas de la consola para README y docs (requiere `npm run start -- -p 3112`).
import { chromium } from "playwright";
const url = process.argv[2] ?? "http://localhost:3112";
const C = "docs/capturas/";
const b = await chromium.launch();
const errs = [];
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto(url);
await p.waitForTimeout(2500); // el logo de la cabecera está animado
await p.screenshot({ path: C + "consola-inicio.png" });
await p.getByRole("button", { name: "Velocidad por 10" }).click();
await p.getByRole("button", { name: "Iniciar", exact: true }).click();
await p.getByText(/¿La llamada F1/).waitFor({ timeout: 40000 });
await p.waitForTimeout(500);
await p.screenshot({ path: C + "consola-decision.png" });
await p.keyboard.press("d");
await p.getByText(/¿La llamada B2/).waitFor({ timeout: 40000 });
await p.keyboard.press("m");
await p.getByText(/27 de 27/).waitFor({ timeout: 40000 });
await p.waitForTimeout(1500);
await p.getByRole("button", { name: /INC-05,/ }).first().click(); // marcador del mapa: abre su ficha
await p.getByRole("button", { name: "¿La persona respira? ¿Está consciente?" }).click();
await p.waitForTimeout(400);
await p.screenshot({ path: C + "consola-final.png" });
await p.getByRole("button", { name: /Aprobar y enviar: SMS en árabe/ }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: C + "consola-acciones.png" });
await p.getByRole("button", { name: "Alejar" }).click();
await p.getByRole("button", { name: "Alejar" }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: C + "consola-alejado.png" });
await p.getByRole("button", { name: "Campanillas", exact: true }).click();
await p.getByRole("button", { name: /INC-01,/ }).first().click();
await p.waitForTimeout(1200);
await p.screenshot({ path: C + "consola-campanillas.png" });
await p.getByRole("button", { name: "Cambiar a modo claro" }).click();
await p.getByRole("button", { name: "Toda la zona", exact: true }).click();
await p.waitForTimeout(2500);
await p.screenshot({ path: C + "consola-claro.png" });
await p.getByRole("button", { name: "Cambiar a modo oscuro" }).click();
await p.getByRole("button", { name: "Cómo funciona" }).first().click();
await p.waitForTimeout(300);
await p.screenshot({ path: C + "consola-ayuda.png" });

const m = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
m.on("pageerror", (e) => errs.push(e.message));
await m.goto(url);
await m.getByRole("button", { name: "Velocidad por 10" }).click();
await m.getByRole("button", { name: "Iniciar", exact: true }).click();
await m.getByText(/¿La llamada F1/).waitFor({ timeout: 40000 });
await m.screenshot({ path: C + "movil-decision.png" });
await m.keyboard.press("d");
await m.waitForTimeout(600);
await m.screenshot({ path: C + "movil-mapa.png", clip: { x: 0, y: 0, width: 390, height: 1100 }, fullPage: true });
const over = await m.evaluate(() => document.documentElement.scrollWidth - innerWidth);
await b.close();
if (over > 0 || errs.length) { console.error("FALLA", { over, errs }); process.exit(1); }
console.log("Capturas OK en", C);
